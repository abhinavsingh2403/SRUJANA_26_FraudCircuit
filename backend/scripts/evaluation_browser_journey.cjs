/* Run against an isolated, initially empty local database. */
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const base=process.env.TRACEGUARD_TEST_URL;
if (!base) throw new Error('Set TRACEGUARD_TEST_URL to an isolated test server.');
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.TRACEGUARD_CHROMIUM?{executablePath:process.env.TRACEGUARD_CHROMIUM,args:['--no-sandbox','--no-zygote','--single-process','--in-process-gpu','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']}: {})});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 const checks=[];
 const loaded=()=>page.waitForFunction(()=>document.querySelector('#evaluation-content').hidden===false);
 try {
  await page.goto(base+'/#/evaluation'); await loaded();
  assert.match(await page.locator('#evaluation-metrics').innerText(),/Not available/);
  assert.match(await page.locator('#evaluation-run-count').innerText(),/No recorded runs/);
  checks.push('empty state has no invented performance or completion metrics');
  let r=await page.request.post(base+'/api/scenarios/rapid-pass-through/replay',{data:{}}); assert.equal(r.status(),200);
  const cid=(await r.json()).cases[0].case_id;
  await page.request.post(base+'/api/scenarios/legitimate-high-volume/replay',{data:{}});
  await page.locator('#evaluation-refresh').click(); await loaded();
  assert.equal(await page.locator('#evaluation-runs tr').count(),2);
  await page.locator('#audit-inspector-input').fill(cid); await page.locator('#audit-inspector-btn').click();
  await page.waitForFunction(()=>document.querySelector('#audit-inspector-result').textContent.includes('No review events'));
  checks.push('real run provenance including a zero-case run; no-events audit state');
  await page.request.patch(base+`/api/cases/${cid}/review`,{data:{status:'CLOSED',outcome:'INCONCLUSIVE',reviewer:'Browser test'}});
  await page.locator('#audit-inspector-btn').click();
  await page.waitForFunction(()=>document.querySelector('#audit-inspector-result').textContent.includes('Review chain valid'));
  const dl=page.waitForEvent('download');await page.locator('#audit-export').click();
  const file=await dl; const text=fs.readFileSync(await file.path(),'utf8'); assert.equal(JSON.parse(text).case_id,cid);
  checks.push('real review verification and valid JSON export');
  await page.locator('#evaluation-refresh').click(); await loaded();
  assert.match(await page.locator('#evaluation-outcomes').innerText(),/Inconclusive: 1/);
  await page.selectOption('#evaluation-source','uploaded_csv'); await loaded();
  assert.match(await page.locator('#evaluation-run-count').innerText(),/No recorded runs/);
  await page.selectOption('#evaluation-source','synthetic_fixture'); await loaded();
  assert.equal(await page.locator('#evaluation-runs tr').count(),2);
  const snapshot=page.waitForEvent('download');await page.locator('#evaluation-export').click();
  const data=JSON.parse(fs.readFileSync(await (await snapshot).path(),'utf8'));assert.equal(data.scope,'synthetic_fixture');assert.equal(data.cases.closed,1);
  checks.push('source filter, live review counters and scoped snapshot export');
  await page.route('**/api/evaluation/summary*',route=>route.fulfill({status:503,contentType:'application/json',body:'{"detail":"test unavailable"}'}));
  await page.locator('#evaluation-refresh').click();
  await page.waitForFunction(()=>document.querySelector('#evaluation-status').textContent.includes('Evidence unavailable'));
  assert.equal(await page.locator('#evaluation-content').isVisible(),false);
  assert.equal(await page.locator('#evaluation-export').isDisabled(),true);
  await page.unroute('**/api/evaluation/summary*');await page.locator('#evaluation-refresh').click();await loaded();
  checks.push('failure clears stale figures and disables export; refresh recovers');
  await page.locator('#audit-inspector-input').fill('missing-case');await page.locator('#audit-inspector-btn').click();
  await page.waitForFunction(()=>document.querySelector('#audit-inspector-result').textContent.includes('404'));
  assert.equal(await page.locator('#audit-export').isDisabled(),true);
  await page.locator('#audit-inspector-input').fill(cid);await page.locator('#audit-inspector-btn').click();
  await page.waitForFunction(()=>document.querySelector('#audit-inspector-result').textContent.includes('Review chain valid'));
  await page.screenshot({path:'artifacts/evaluation_desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth),true);
  await page.screenshot({path:'artifacts/evaluation_mobile.png',fullPage:true});
  checks.push('unknown-case error and responsive desktop/mobile layout');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:true,checks,page_errors:errors},null,2));
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
